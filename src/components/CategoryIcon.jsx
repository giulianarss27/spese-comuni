export default function CategoryIcon({ category = 'altro', size = 40, noBg = false }) {
  const cat = CATEGORIES[category];
  const color = cat?.color || SESSION_ICON_COLORS[category] || '#5F5E5A';
  const iconSize = Math.round(size * (noBg ? 1 : 0.5));

  if (noBg) {
    return (
      <div style={{ width: iconSize, height: iconSize, color, flexShrink: 0 }}>
        {icons[category] || icons.altro}
      </div>
    );
  }

  return (
    <div
      style={{
        width: size,
        height: size,
        borderRadius: '50%',
        backgroundColor: color,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        flexShrink: 0,
        color: '#fff',
      }}
    >
      <div style={{ width: iconSize, height: iconSize }}>
        {icons[category] || icons.altro}
      </div>
    </div>
  );
}
